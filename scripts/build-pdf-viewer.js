/**
 * Builds src/viewer/pdfViewerHtml.ts, a self-contained HTML page (pdf.js inlined)
 * used by the in-app PDF viewer on Android. Run: npm run build:viewer
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const template = fs.readFileSync(path.join(__dirname, 'viewer-template.html'), 'utf8');
const pdfjs = fs.readFileSync(path.join(root, 'vendor/pdfjs/pdf.min.js'), 'utf8');
const worker = fs.readFileSync(path.join(root, 'vendor/pdfjs/pdf.worker.min.js'), 'utf8');

const safeScript = pdfjs.replace(/<\/script/gi, '<\\/script');
const workerLiteral = JSON.stringify(worker).replace(/<\//g, '<\\/');

const html = template
  .replace('/*PDFJS*/', () => safeScript)
  .replace('/*WORKER*/""', () => workerLiteral);

const out =
  '// AUTO-GENERATED by scripts/build-pdf-viewer.js. Do not edit.\n' +
  '// Contains pdf.js 3.11.174 (Apache-2.0, see vendor/pdfjs/LICENSE).\n' +
  '/* eslint-disable */\n' +
  'export const PDF_VIEWER_HTML: string = ' +
  JSON.stringify(html) +
  ';\n';

fs.writeFileSync(path.join(root, 'src/viewer/pdfViewerHtml.ts'), out);
fs.writeFileSync(path.join(root, 'vendor/pdfjs/viewer.html'), html);
console.log('Wrote src/viewer/pdfViewerHtml.ts (' + Math.round(out.length / 1024) + ' KB)');
